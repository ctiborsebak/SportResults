import SwiftUI

public extension Color {
    enum Accent {
        public static let mint = Color(.mintAccent)
        public static let blue = Color(.blueAccent)
    }

    enum Text {
        public static let primary = Color(.textPrimary)
        public static let secondary = Color(.textSecondary)
        public static let tertiary = Color(.textTertiary)
        public static let mint = Color(.textMintAccent)
        public static let blue = Color(.textBlueAccent)
    }
}
